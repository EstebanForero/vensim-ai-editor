import { equationCausalEdges } from "../model/derived.js";
import { allVariables, type Model } from "../model/types.js";

export interface SignedEdge {
  to: string;
  sign: 1 | -1;
}

/**
 * Builds the directed, signed causal graph used for loop detection, from both places a model
 * states its own causality: connectors carry their own polarity, and each flow contributes an
 * edge into the stock(s) it touches — "+" for an inflow (raises the stock), "-" for an outflow
 * (lowers it). A cycle through this graph is a feedback loop; the product of the signs traversed
 * determines whether it's reinforcing or balancing.
 *
 * The equations are read as well as the arrows, and that is not a belt-and-braces extra: arrows
 * are *drawn*, so a model that arrived any other way — typed in, imported from a `.mdl` whose
 * sketch is empty or partial, generated by an AI that added variables and equations but no
 * relations — has no arrows to read and would be reported as having no feedback structure at all.
 * Reading the equations too makes the answer a property of the model rather than of its drawing.
 *
 * **One edge per pair, whichever way it was stated.** A causal relation between two variables is
 * one relation, and the same one can be written down more than once: a relation drawn from a
 * flow's valve back to the stock it drains restates the flow's own pipe, with an invented
 * polarity. Left as two edges that pair is two loops — one of them the reverse of the truth — and
 * a plain drain then reads as an R loop and a B loop on one stock, which is exactly Limits to
 * Growth. The flow's own edge wins such a collision, being the model's semantics rather than an
 * annotation of them; the equations are reached for only where neither of the other two applies.
 */
export function buildSignedGraph(model: Model): Map<string, SignedEdge[]> {
  const adjacency = new Map<string, SignedEdge[]>();
  for (const v of allVariables(model)) adjacency.set(v.id, []);

  const connect = (from: string, to: string, sign: 1 | -1) => {
    const edges = adjacency.get(from);
    if (!edges || edges.some((e) => e.to === to)) return;
    edges.push({ to, sign });
  };

  for (const f of model.flows) {
    if (f.to) connect(f.id, f.to, 1);
    if (f.from) connect(f.id, f.from, -1);
  }
  for (const c of model.connectors) {
    connect(c.from, c.to, c.polarity === "-" ? -1 : 1);
  }
  for (const e of equationCausalEdges(model)) {
    connect(e.from.id, e.to.id, e.polarity === "-" ? -1 : 1);
  }

  return adjacency;
}
