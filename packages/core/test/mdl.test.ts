/** The `10,` shape id this editor's writer assigned to a variable by its exact name. */
function idOf(mdlText: string, name: string): string {
  const line = mdlText.split("\n").find((l) => l.startsWith("10,") && l.split(",")[2] === name)!;
  return line.split(",")[1]!;
}

const SAMPLE_MDL = `{UTF-8}
Population= INTEG (
	Births-Deaths,
		100) ~~|

Births= Population*Birth Rate ~~|

Deaths= Population*Death Rate ~~|

Birth Rate= 0.02 ~~|

Death Rate= 0.01 ~~|

********************************************************
	.Control
********************************************************~
		Simulation Control Parameters
	|

FINAL TIME  = 100
	~	Month
	~	The final time for the simulation.
	|

INITIAL TIME  = 0
	~	Month
	~	The initial time for the simulation.
	|

SAVEPER  =
        TIME STEP
	~	Month [0,?]
	~	The frequency with which output is stored.
	|

TIME STEP  = 0.25
	~	Month [0,?]
	~	The time step for the simulation.
	|

\\\\\\---/// Sketch information - do not modify anything except names
V300  Do not put anything below this section - it will be ignored
*View 1
$192-192-192,0,Times New Roman|12||0-0-0|0-0-0|0-0-255|-1--1--1|-1--1--1|96,96,100,0
10,1,Population,300,200,40,20,3,3,0,0,0,0,0,0
10,2,Births,150,200,30,15,40,3,0,0,-1,0,0,0
10,3,Deaths,450,200,30,15,40,3,0,0,-1,0,0,0
10,6,Birth Rate,150,280,30,15,8,3,0,0,-1,0,0,0
1,7,6,2,1,0,0,0,0,64,0,-1--1--1,,1|(150,240)|
10,8,Death Rate,450,280,30,15,8,3,0,0,-1,0,0,0
1,9,8,3,1,0,0,0,0,64,0,-1--1--1,,1|(450,240)|
///---\\\\\\
`;

describe("mdl codec", () => {
  test("parses a classic population model", () => {
    const model = parseMdl(SAMPLE_MDL);
    expect(model.stocks.map((s) => s.name)).toEqual(["Population"]);
    expect(model.flows.map((f) => f.name).sort()).toEqual(["Births", "Deaths"]);
    expect(model.auxiliaries.map((a) => a.name).sort()).toEqual(["Birth Rate", "Death Rate"]);
    expect(model.simSpec.stopTime).toBe(100);
    expect(model.simSpec.dt).toBe(0.25);

    // Sketch coordinates are the shape's *center*, and w,h (40,20 here) are *half*-width/
    // half-height per Vensim's own sketch-format reference — so the full box is 80x40, and
    // this editor's own Position convention (top-left) must convert both.
    const pop = model.stocks[0]!;
    expect(pop.pos).toEqual({ x: 260, y: 180 });
    expect(model.connectors.length).toBeGreaterThan(0);
  });

  // Regression: found while verifying tools/xmutil-bridge's output (real Vensim-convention
  // .mdl, generated by Vensim's own creator's xmutil) through this parser — a stock's INTEG
  // net-flow expression wrapped across a line-continuation (`\` at end of line, a real Vensim
  // convention for long equations, confirmed in xmutil's own MDLGenerator.cpp) silently lost
  // its flows entirely (parsed as zero inflows/outflows) instead of erroring, because the
  // continued text was never rejoined before parsing.
  test("joins a line-continued equation (trailing `\\`) instead of truncating it", () => {
    const mdl = `{UTF-8}
Inventario= INTEG (
	Recepcion -\\
		 Venta, 60)
	~	bicicletas
	~
	|

Recepcion= Pedido / Tiempo_de_entrega ~~|

Venta= MIN(Demanda, Inventario / 1) ~~|

Pedido= MAX(0, (Deseado - Inventario) /\\
		 Ajuste)
	~	bicicletas/dia
	~
	|

Deseado= 100 ~~|
Tiempo_de_entrega= 5 ~~|
Ajuste= 10 ~~|
Demanda= 8 ~~|

********************************************************
	.Control
********************************************************~
		Simulation Control Parameters
	|
FINAL TIME  = 60
	~
	~
	|
INITIAL TIME  = 0
	~
	~
	|
TIME STEP  = 0.25
	~
	~
	|
`;
    const model = parseMdl(mdl);
    expect(model.flows.map((f) => f.name).sort()).toEqual(["Recepcion", "Venta"]);
    const stock = model.stocks.find((s) => s.name === "Inventario")!;
    expect(stock.inflows).toHaveLength(1);
    expect(stock.outflows).toHaveLength(1);
    const pedido = model.auxiliaries.find((a) => a.name === "Pedido")!;
    expect(pedido.equation).toContain("Deseado");
    expect(pedido.equation).toContain("Ajuste");
    expect(simulate(model).series["Inventario"]?.at(-1)).toBeCloseTo(1.9607843137254903, 6);
  });

  test("parsed model simulates sensibly", () => {
    const model = parseMdl(SAMPLE_MDL);
    model.simSpec.integrationMethod = "rk4";
    const result = simulate(model);
    const last = result.series["Population"]!.at(-1)!;
    // net growth rate 1%/month over 100 months
    expect(last).toBeGreaterThan(100);
    expect(last).toBeCloseTo(100 * Math.exp(0.01 * 100), 0);
  });

  test("round-trips a hand-built model through write -> parse", () => {
    const model = createEmptyModel("RoundTrip");
    const stock = addStock(model, { name: "Inventory", initialEquation: "50", units: "Widgets" });
    addFlow(model, { name: "Production", equation: "10", to: stock.id, units: "Widgets/Month" });
    addFlow(model, { name: "Shipping", equation: "Inventory*0.1", from: stock.id, units: "Widgets/Month" });
    addAuxiliary(model, { name: "Target", equation: "200" });

    const mdlText = writeMdl(model);
    const reparsed = parseMdl(mdlText);

    expect(reparsed.stocks.map((s) => s.name).sort()).toEqual(["Inventory"]);
    expect(reparsed.flows.map((f) => f.name).sort()).toEqual(["Production", "Shipping"]);
    expect(reparsed.auxiliaries.map((a) => a.name).sort()).toEqual(["Target"]);

    const again = parseMdl(writeMdl(reparsed));
    expect(again.stocks.length).toBe(reparsed.stocks.length);
    expect(again.flows.length).toBe(reparsed.flows.length);
    expect(again.auxiliaries.length).toBe(reparsed.auxiliaries.length);
  });

  test("round-trips a flow connecting two real stocks without duplicating it", () => {
    // A flow between two actual stocks (not a cloud on either end) appears in *both* stocks'
    // INTEG net-flow expressions on write — "-Flow" in the source stock, "+Flow" in the sink
    // stock. The parser previously created the flow the first time it saw either term (with
    // only that one end set), then treated the second stock's term as an unrelated inline
    // expression once the name was already "claimed", materializing a bogus second anonymous
    // flow — so the flow was never actually connected to both stocks after a round-trip.
    const model = createEmptyModel("TwoStockFlow");
    const a = addStock(model, { name: "A", initialEquation: "100" });
    const b = addStock(model, { name: "B", initialEquation: "0" });
    addFlow(model, { name: "Transfer", equation: "5", from: a.id, to: b.id });

    const reparsed = parseMdl(writeMdl(model));

    expect(reparsed.flows).toHaveLength(1);
    const flow = reparsed.flows[0]!;
    expect(flow.name).toBe("Transfer");
    const fromStock = reparsed.stocks.find((s) => s.id === flow.from);
    const toStock = reparsed.stocks.find((s) => s.id === flow.to);
    expect(fromStock?.name).toBe("A");
    expect(toStock?.name).toBe("B");
  });

  // Regression: a stock's INTEG net-flow term list was built by raw string concatenation
  // ("+Name"/"-Name") instead of going through the expression printer, so it was the one place
  // in the writer that never quoted a multi-word flow name. Vensim can't parse an unquoted
  // multi-word name inside INTEG's argument, so it silently fails to link the flow to its
  // stock — the flow's own definition line is still perfectly valid on its own, so the visible
  // symptom in a real Vensim session is the flow rendering as an unattached "shadow" variable
  // near the stock (no valve icon, no pipe), not a parse error. Every prior test used
  // single-word flow names, so this never showed up until a real multi-word name did.
  test("quotes a multi-word flow name inside its stock's INTEG net-flow expression", () => {
    const model = createEmptyModel("QuotedIntegTerm");
    const stock = addStock(model, { name: "Inventory", initialEquation: "50" });
    addFlow(model, { name: "Order Fulfillment", equation: "10", to: stock.id });
    addFlow(model, { name: "Customer Returns", equation: "1", to: stock.id });
    addFlow(model, { name: "Damage Loss", equation: "1", from: stock.id });

    const mdlText = writeMdl(model);
    expect(mdlText).toContain('"Order Fulfillment"');
    expect(mdlText).toContain('"Customer Returns"');
    expect(mdlText).toContain('"Damage Loss"');
    // Not just present anywhere — specifically quoted where it's referenced inside INTEG.
    expect(mdlText).toMatch(/INTEG \(\s*"Order Fulfillment" \+"Customer Returns" -"Damage Loss"/);

    const reparsed = parseMdl(mdlText);
    expect(reparsed.flows).toHaveLength(3);
    const stockAfter = reparsed.stocks.find((s) => s.name === "Inventory")!;
    expect(stockAfter.inflows).toHaveLength(2);
    expect(stockAfter.outflows).toHaveLength(1);
  });

  // Regression: real Vensim's own Equations view showed a mojibake replacement character for a
  // flow name referenced with an accent (e.g. "Recepción") inside a QUOTED reference (the
  // stock's own INTEG argument), while the exact same name's unquoted definition line displayed
  // fine — consistent with Vensim's quoted-name reading path using a codepage-sensitive routine
  // distinct from its unquoted-identifier path, so a quoted accented reference can silently
  // resolve to a different (phantom, always-zero) variable than the one its own definition line
  // created. A live-Vensim comparison against this exact scenario showed the accented flow's
  // contribution reading as if it were entirely absent from the simulation. Stripping diacritics
  // at export time, everywhere a name is written, keeps the definition and every reference to it
  // byte-identical ASCII.
  test("strips accents from variable names everywhere they're written, including quoted references", () => {
    const model = createEmptyModel("AccentedNames");
    const stock = addStock(model, { name: "Inventario de bicicletas", initialEquation: "60" });
    addFlow(model, { name: "Recepción de bicicletas", equation: "5", to: stock.id });
    addFlow(model, { name: "Venta", equation: '"Recepción de bicicletas" * 0.5', from: stock.id });

    const mdlText = writeMdl(model);
    expect(mdlText).not.toMatch(/[À-ſ]/); // no Latin-1 Supplement / Latin Extended-A accented letters anywhere
    expect(mdlText).toContain("Recepcion de bicicletas=");
    expect(mdlText).toContain('"Recepcion de bicicletas" -Venta'); // the stock's INTEG term
    expect(mdlText).toContain('"Recepcion de bicicletas" * 0.5'); // the quoted reference inside Venta's own equation

    const reparsed = parseMdl(mdlText);
    expect(reparsed.flows.map((f) => f.name).sort()).toEqual(["Recepcion de bicicletas", "Venta"]);
    const stockAfter = reparsed.stocks[0]!;
    expect(stockAfter.inflows).toHaveLength(1);
    expect(stockAfter.outflows).toHaveLength(1);
  });

  // Regression: the accent-stripping fix above only rewrote QUOTED references, on the (false)
  // assumption that an accented name could never legally appear unquoted in equation text. It
  // can: this editor's own equation parser tolerates a bare multi-word/accented reference typed
  // directly (by a user or the AI) without quotes, matching known variable names contextually —
  // so a real model built that way (an unquoted reference to an accented name from a DIFFERENT
  // variable's equation) hit the exact bug this whole mechanism exists to prevent: the export's
  // accent-stripped definition line and the untouched unquoted reference became two different
  // strings, which Vensim treats as two different variables — the referenced one undefined, so
  // it shows up as an unattached "shadow" placeholder carrying the actual connection, while the
  // real, correctly-placed box sits with nothing wired into it. (Found from a live Vensim
  // session's actual mojibake'd Equations view, not a hypothetical.)
  test("rewrites an unquoted accented reference inside a DIFFERENT variable's equation too", () => {
    const model = createEmptyModel("UnquotedAccentedRef");
    addAuxiliary(model, { name: "Efecto de recomendación", equation: "1" });
    addAuxiliary(model, { name: "Efectividad de marketing", equation: "2" });
    // Typed the way this editor's own lenient parser accepts: no quotes around either
    // multi-word/accented reference.
    addAuxiliary(model, {
      name: "Adquisicion de suscriptores",
      equation: "Efecto de recomendación + Efectividad de marketing",
    });

    const mdlText = writeMdl(model);
    expect(mdlText).not.toMatch(/[À-ſ]/);
    // The reference must use the SAME spelling as the definition line, whichever form (quoted
    // or bare) each ends up in.
    expect(mdlText).toContain("Efecto de recomendacion=");
    expect(mdlText).toMatch(/Adquisicion de suscriptores= .*Efecto de recomendacion/);
    expect(mdlText).not.toContain("recomendación"); // the accented spelling must not survive anywhere

    const reparsed = parseMdl(mdlText);
    const adquisicion = reparsed.auxiliaries.find((a) => a.name === "Adquisicion de suscriptores")!;
    // Round-trips back into a model where the reference actually resolves to the real variable —
    // not a name Vensim (or this editor's own parser) would treat as a second, undefined one.
    expect(reparsed.auxiliaries.some((a) => a.name === "Efecto de recomendacion")).toBe(true);
    expect(adquisicion.equation).toContain("Efecto de recomendacion");
  });

  // Regression: real Vensim's own `12,` comment-record reader only reads the following line as
  // the box's text when bit 2 (value 4) of the `bits` field (right after shape) is set —
  // otherwise it treats the text as an unrelated following record instead, so the note loads
  // empty in Vensim. commentRecord wrote `bits=3` (no bit 2), so a freeform note or a full loop
  // annotation sentence never actually carried its text into Vensim, even though this editor's
  // own parser (which doesn't check `bits` at all) round-tripped it fine — masking the bug in
  // every prior test. loopBadgeRecord's small "R"/"B" circle already used `bits=7` correctly,
  // which is why only the badge (not the full sentence) was visible in a real Vensim session.
  test("sets the comment record's bits field so real Vensim reads its text line", () => {
    const model = createEmptyModel("NoteExport");
    addComment(model, { text: "Hand-written note", pos: { x: 10, y: 20 }, size: { width: 100, height: 40 } });

    const mdlText = writeMdl(model);
    const line = mdlText.split("\n").find((l) => l.startsWith("12,") && !l.includes(",48,"))!;
    const bits = Number(line.split(",")[8]);
    expect(bits & 4).toBe(4);
  });

  test("writes R/B loop comment annotations and curved relation arrows for native Vensim", () => {
    const model = createEmptyModel("LoopExport");
    const stock = addStock(model, { name: "Population", initialEquation: "100", pos: { x: 0, y: 0 } });
    const births = addFlow(model, { name: "Births", equation: "Population * Birth Rate", to: stock.id, pos: { x: 150, y: 100 } });
    addAuxiliary(model, { name: "Birth Rate", equation: "0.02", pos: { x: 0, y: 200 } });
    addConnector(model, { from: "Population", to: births.id });
    addConnector(model, { from: "Birth Rate", to: births.id });

    const mdlText = writeMdl(model);

    // Loop badge shows up as a freestanding `12,` text record (shape code 0 — a plain text
    // box, not a built-in icon like Vensim's own cloud glyph) with a bare "R"/"B", matching
    // native Vensim's own loop-indicator convention (see example-compatibility/flow-diagram.mdl).
    expect(mdlText).toMatch(/^12,\d+,0,-?\d+,-?\d+,27,27,4,7,/m);
    expect(mdlText).toMatch(/^R\d+$/m);

    // Connector arrows carry field codes matching a real causal/info-link arrow (see
    // example-compatibility/flow-diagram.mdl) and a non-origin bend waypoint.
    const connectorLines = mdlText.split("\n").filter((l) => l.startsWith("1,") && l.includes(",1,0,43,0,0,192,0,"));
    expect(connectorLines.length).toBeGreaterThan(0);
    for (const line of connectorLines) expect(line).not.toContain("|(0,0)|");

    // "Population -> Births" must target the flow's *valve* shape id, not its name-label id —
    // confirmed against every real causal-arrow-into-a-flow in both example-compatibility
    // files, which always address the valve. The valve is the `11,` line right before the
    // flow's own `10,` name-label line in this editor's own writer output.
    const lines = mdlText.split("\n");
    const labelLine = lines.find((l) => l.startsWith("10,") && l.includes(",Births,"))!;
    const valveLine = lines[lines.indexOf(labelLine) - 1]!;
    expect(valveLine.startsWith("11,")).toBe(true);
    const valveId = valveLine.split(",")[1];
    const popToBirths = connectorLines.find((l) => l.split(",")[2] === idOf(mdlText, "Population"))!;
    expect(popToBirths.split(",")[3]).toBe(valveId);

    // The file must still parse cleanly — comments/curve points don't confuse the codec.
    const reparsed = parseMdl(mdlText);
    expect(reparsed.stocks).toHaveLength(1);
    expect(reparsed.connectors.length).toBeGreaterThan(0);
  });

  test("reads a real Vensim export (example-compatibility/flow-diagram.mdl) faithfully", () => {
    // A hand-exported-from-Vensim rabbit-population model — the reference for this editor's
    // compatibility with files it did not itself write. In particular, its causal arrows are
    // drawn *into a flow's valve icon* (a separate sketch shape from the flow's name label),
    // which is the normal way Vensim draws "this variable affects this flow" and must resolve
    // to the flow's name for loop detection to see the model's real feedback structure.
    const fixturePath = join(import.meta.dir, "..", "..", "..", "example-compatibility", "flow-diagram.mdl");
    const model = parseMdl(readFileSync(fixturePath, "utf-8"));

    expect(model.stocks.map((s) => s.name)).toEqual(["Poblacion"]);
    expect(model.flows.map((f) => f.name).sort()).toEqual(["muertes", "nacimientos"]);
    expect(model.auxiliaries.map((a) => a.name).sort()).toEqual(["tasa mortalidad", "tasa nacimientos"]);

    // Every causal arrow into a flow's valve must resolve to that flow, not get dropped.
    const connectorPairs = model.connectors
      .map((c) => {
        const from = [...model.stocks, ...model.flows, ...model.auxiliaries].find((v) => v.id === c.from)?.name;
        const to = [...model.stocks, ...model.flows, ...model.auxiliaries].find((v) => v.id === c.to)?.name;
        return `${from}->${to}`;
      })
      .sort();
    expect(connectorPairs).toEqual(["Poblacion->muertes", "Poblacion->nacimientos", "tasa mortalidad->muertes", "tasa nacimientos->nacimientos"]);

    // Flow-pipe geometry arrows (valve <-> stock/cloud) must NOT become spurious connectors.
    expect(model.connectors).toHaveLength(4);

    const loops = detectLoops(model);
    expect(loops.map((l) => l.polarity).sort()).toEqual(["B", "R"]);

    const sim = simulate(model);
    expect(sim.series["Poblacion"]?.at(-1)).toBeGreaterThan(0);

    // Round-trips: re-exporting and re-parsing keeps the same causal structure and simulates
    // the same way (the loop badges/graph pad this editor adds on export must not confuse it).
    const reExported = parseMdl(writeMdl(model));
    expect(reExported.connectors).toHaveLength(4);
    expect(detectLoops(reExported).map((l) => l.polarity).sort()).toEqual(["B", "R"]);
    expect(simulate(reExported).series["Poblacion"]?.at(-1)).toBeCloseTo(sim.series["Poblacion"]!.at(-1)!, 6);
  });

  test("exports 10,/11,/12, sketch records with the same field count real Vensim uses", () => {
    // Confirmed by counting comma-separated fields on every `10,`/`11,`/`12,` line in *two*
    // independently real-Vensim-exported files (example-compatibility/flow-diagram.mdl and
    // aitraining.mdl, from separate sessions): every one has exactly 21 fields for `10,`/`11,`
    // and 21 for a plain `12,` box (id,name/code,x,y,w,h,sh,bits, then 12 more trailing
    // fields). This editor's writer previously emitted only 15 fields for its own dynamically
    // generated `10,` records (stocks/auxiliaries/flow labels) — a genuinely truncated,
    // non-conformant line, not just a cosmetically different one, which is a very plausible
    // reason a real Vensim install would render an opened file as visually broken.
    const model = createEmptyModel("FieldCount");
    const a = addStock(model, { name: "A" });
    const b = addStock(model, { name: "B" });
    addFlow(model, { name: "F", from: a.id, to: b.id });
    addAuxiliary(model, { name: "Aux", equation: "1" });

    const sketch = writeMdl(model).split("Sketch information")[1]!;
    const recordLines = sketch.split("\n").filter((l) => /^(10|11|12),/.test(l));
    expect(recordLines.length).toBeGreaterThan(0);
    for (const line of recordLines) {
      expect(line.split(",")).toHaveLength(21);
    }
  });

  // Regression: Vensim recognizes a flow's valve and its own name-label as one paired "Rate"
  // PURELY by numeric uid adjacency (valve_uid, valve_uid + 1) — confirmed straight from Vensim's
  // own xmutil converter source (src/Mdl/MDLGenerator.cpp: "Vensim draws a flow as an attached
  // valve immediately followed by the flow's own variable record, and consumers resolve the pair
  // by that adjacency alone"). This writer previously assigned every variable's id in one pass
  // and appended each flow's valve id afterward from a separate, later counter, so the two ids
  // were textually adjacent in the emitted file (which the older, weaker test below checked) but
  // NOT numerically consecutive — which is what Vensim itself actually keys off, and which is
  // very plausibly why a real Vensim resave kept orphaning the label into a disconnected box.
  test("a flow's valve id and its own name-label id are numerically consecutive", () => {
    const model = createEmptyModel("Adjacency");
    const a = addStock(model, { name: "A" });
    const b = addStock(model, { name: "B" });
    // Stocks are declared before the flow so a pre-flow id pass (the old, buggy scheme) would
    // have already consumed ids 1 and 2 before ever reaching the flow — exactly the shape that
    // used to break adjacency.
    addFlow(model, { name: "Transfer", from: a.id, to: b.id });
    addAuxiliary(model, { name: "Aux", equation: "1" });

    const mdlText = writeMdl(model);
    const lines = mdlText.split("\n");
    const labelLine = lines.find((l) => l.startsWith("10,") && l.split(",")[2] === "Transfer")!;
    const valveLine = lines.find((l) => l.startsWith("11,"))!;
    const labelId = Number(labelLine.split(",")[1]);
    const valveId = Number(valveLine.split(",")[1]);
    expect(labelId).toBe(valveId + 1);
  });
});
